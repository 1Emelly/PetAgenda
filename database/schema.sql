-- =====================================================
-- PETAGENDA
-- Sistema de Gerenciamento de Clínicas Veterinárias
-- Banco de Dados: PostgreSQL
-- =====================================================


-- =====================================================
-- 1. USUÁRIOS
-- =====================================================

CREATE TABLE IF NOT EXISTS usuarios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    nome VARCHAR(150) NOT NULL,

    email VARCHAR(150) NOT NULL UNIQUE,

    senha_hash TEXT NOT NULL,

    perfil VARCHAR(20) NOT NULL
        CHECK (
            perfil IN (
                'Administrador',
                'Secretario',
                'Veterinario',
                'Tutor'
            )
        ),

    ativo BOOLEAN NOT NULL DEFAULT TRUE,

    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- =====================================================
-- 2. TUTORES
-- =====================================================

CREATE TABLE IF NOT EXISTS tutores (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    usuario_id INTEGER UNIQUE
        REFERENCES usuarios(id)
        ON DELETE SET NULL,

    nome VARCHAR(150) NOT NULL,

    email VARCHAR(150),

    telefone VARCHAR(20),

    endereco TEXT,

    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- =====================================================
-- 3. VETERINÁRIOS
-- =====================================================

CREATE TABLE IF NOT EXISTS veterinarios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    usuario_id INTEGER UNIQUE
        REFERENCES usuarios(id)
        ON DELETE SET NULL,

    nome VARCHAR(150) NOT NULL,

    crmv VARCHAR(30) NOT NULL UNIQUE,

    especialidade VARCHAR(100),

    telefone VARCHAR(20),

    ativo BOOLEAN NOT NULL DEFAULT TRUE,

    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- =====================================================
-- 4. ANIMAIS
-- =====================================================

CREATE TABLE IF NOT EXISTS animais (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    tutor_id INTEGER NOT NULL
        REFERENCES tutores(id)
        ON DELETE RESTRICT,

    nome VARCHAR(100) NOT NULL,

    especie VARCHAR(80) NOT NULL,

    raca VARCHAR(100),

    sexo VARCHAR(20)
        CHECK (
            sexo IN (
                'Macho',
                'Femea'
            )
        ),

    data_nascimento DATE,

    peso NUMERIC(6,2)
        CHECK (peso IS NULL OR peso > 0),

    observacoes TEXT,

    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- =====================================================
-- 5. CONSULTAS
-- =====================================================

CREATE TABLE IF NOT EXISTS consultas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    animal_id INTEGER NOT NULL
        REFERENCES animais(id)
        ON DELETE RESTRICT,

    veterinario_id INTEGER NOT NULL
        REFERENCES veterinarios(id)
        ON DELETE RESTRICT,

    data_hora TIMESTAMP NOT NULL,

    motivo TEXT,

    status VARCHAR(30) NOT NULL DEFAULT 'Agendada'
        CHECK (
            status IN (
                'Agendada',
                'Confirmada',
                'Em atendimento',
                'Concluida',
                'Cancelada'
            )
        ),

    observacoes TEXT,

    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- =====================================================
-- 6. ATENDIMENTOS
-- =====================================================

CREATE TABLE IF NOT EXISTS atendimentos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    consulta_id INTEGER NOT NULL UNIQUE
        REFERENCES consultas(id)
        ON DELETE RESTRICT,

    diagnostico TEXT,

    procedimentos TEXT,

    observacoes TEXT,

    orientacoes TEXT,

    data_atendimento TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- =====================================================
-- 7. PRONTUÁRIOS
-- =====================================================

CREATE TABLE IF NOT EXISTS prontuarios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    animal_id INTEGER NOT NULL
        REFERENCES animais(id)
        ON DELETE RESTRICT,

    atendimento_id INTEGER NOT NULL UNIQUE
        REFERENCES atendimentos(id)
        ON DELETE RESTRICT,

    descricao TEXT,

    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- =====================================================
-- ÍNDICES PARA CONSULTAS E FILTROS
-- =====================================================

CREATE INDEX IF NOT EXISTS idx_animais_tutor
ON animais(tutor_id);

CREATE INDEX IF NOT EXISTS idx_consultas_animal
ON consultas(animal_id);

CREATE INDEX IF NOT EXISTS idx_consultas_veterinario
ON consultas(veterinario_id);

CREATE INDEX IF NOT EXISTS idx_consultas_data
ON consultas(data_hora);

CREATE INDEX IF NOT EXISTS idx_consultas_status
ON consultas(status);

CREATE INDEX IF NOT EXISTS idx_prontuarios_animal
ON prontuarios(animal_id);


